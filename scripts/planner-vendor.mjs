import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..'),out=resolve(root,'public/js/vendor');
await mkdir(out,{recursive:true});
await build({stdin:{contents:`
export { Delaunay } from 'd3-delaunay';
export { createNoise2D } from 'simplex-noise';
export { default as PoissonDiskSampling } from 'poisson-disk-sampling';
export { default as GeoJSONReader } from 'jsts/org/locationtech/jts/io/GeoJSONReader.js';
export { default as GeoJSONWriter } from 'jsts/org/locationtech/jts/io/GeoJSONWriter.js';
export { default as UnaryUnionOp } from 'jsts/org/locationtech/jts/operation/union/UnaryUnionOp.js';
export { default as OverlayOp } from 'jsts/org/locationtech/jts/operation/overlay/OverlayOp.js';
export { default as BufferOp } from 'jsts/org/locationtech/jts/operation/buffer/BufferOp.js';
export { default as InteriorPointArea } from 'jsts/org/locationtech/jts/algorithm/InteriorPointArea.js';
export { default as GeometryFactory } from 'jsts/org/locationtech/jts/geom/GeometryFactory.js';
export { default as polygonClipping } from 'polygon-clipping';
`,resolveDir:root,sourcefile:'planner-vendor-entry.js'},bundle:true,format:'esm',target:'es2022',minify:true,
  legalComments:'none',outfile:resolve(out,'planner.js'),banner:{js:'// Generated by scripts/planner-vendor.mjs. Pinned sources and licenses: planner-LICENSES.txt.'}});
let notices='Pinned layout planner dependencies. No network is used at generation time.\n\n';
for(const [pkg,license] of [['jsts','../../sources/jsts-2.12.1-EDL.txt'],['polygon-clipping','LICENSE.md'],['splaytree','Readme.md'],['robust-predicates','LICENSE'],['d3-delaunay','LICENSE'],['delaunator','LICENSE'],['simplex-noise','LICENSE'],['poisson-disk-sampling','LICENSE'],['moore','LICENSE.md']]) {
  const dir=resolve(root,'node_modules',pkg),info=JSON.parse(await readFile(resolve(dir,'package.json'),'utf8'));
  notices+=`${pkg} ${info.version}\n${await readFile(resolve(dir,license),'utf8')}\n\n`;
}
await writeFile(resolve(out,'planner-LICENSES.txt'),notices);
console.log('Bundled pinned planner libraries locally.');
